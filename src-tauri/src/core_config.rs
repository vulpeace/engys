//! Shared runtime configuration generation for desktop and Android.
use crate::{
    AppState,
    error::{Error, Result},
    settings::Settings,
};
use serde_yaml::{Mapping, Value};
/// Take the user's profile and overlay the keys the GUI owns. The result is
/// what the core actually runs; the stored profile is never modified.
#[cfg(test)]
pub fn build_runtime_config(profile: &str, s: &Settings) -> Result<String> {
    build_runtime_config_with_apps(profile, s, &[])
}

#[cfg(test)]
pub fn build_runtime_config_with_apps(
    profile: &str,
    s: &Settings,
    apps: &[crate::app_rules::AppRule],
) -> Result<String> {
    build_runtime_config_with_order(profile, s, apps, None)
}

#[cfg(test)]
pub fn build_runtime_config_with_order(
    profile: &str,
    s: &Settings,
    apps: &[crate::app_rules::AppRule],
    order_override: Option<bool>,
) -> Result<String> {
    build_runtime_config_with_groups(profile, s, apps, order_override, &[])
}

pub fn build_runtime_config_with_groups(
    profile: &str,
    s: &Settings,
    apps: &[crate::app_rules::AppRule],
    order_override: Option<bool>,
    groups: &[crate::custom_groups::CustomGroup],
) -> Result<String> {
    let mut root: Mapping = match serde_yaml::from_str::<Value>(profile)? {
        Value::Mapping(m) => m,
        Value::Null => Mapping::new(),
        _ => return Err(Error::msg("Profile is not a YAML mapping")),
    };
    crate::custom_groups::inject(&mut root, groups)?;
    let resolved = s.resolve(&root);
    let s = &resolved;
    let mut set = |k: &str, v: Value| {
        if matches!(k, "external-controller" | "secret")
            || s.overrides.contains(k)
            || !root.contains_key(k)
        {
            root.insert(Value::from(k), v);
        }
    };
    set(
        "external-controller",
        Value::from(format!("127.0.0.1:{}", s.controller_port)),
    );
    set("secret", Value::from(s.secret.clone()));
    if let Some(port) = s.mixed_port {
        set("mixed-port", Value::from(port));
    }
    set("allow-lan", Value::from(s.allow_lan));
    set("ipv6", Value::from(s.ipv6));
    set("log-level", Value::from(s.log_level.clone()));
    set("mode", Value::from(s.mode.clone()));
    if s.mixed_port.is_none() && s.overrides.contains("mixed-port") {
        root.remove("mixed-port");
    }
    // Controller endpoints we don't manage could clash with ours or expose the API.
    for k in [
        "external-controller-tls",
        "external-controller-unix",
        "external-controller-pipe",
    ] {
        root.remove(k);
    }
    // mihomo writes manual group selections into its existing cache.db.
    let mut profile = match root.remove("profile") {
        Some(Value::Mapping(m)) => m,
        _ => Mapping::new(),
    };
    profile.insert(key("store-selected"), Value::from(true));
    root.insert(key("profile"), Value::Mapping(profile));
    apply_tun(&mut root, s);
    crate::app_rules::inject_with_order(&mut root, apps, order_override)?;

    let header =
        "# Generated by Mihomo Client — do not edit; changes are overwritten on every start.\n";
    Ok(format!(
        "{header}{}",
        serde_yaml::to_string(&Value::Mapping(root))?
    ))
}

fn key(k: &str) -> Value {
    Value::from(k)
}

/// Override only client-owned TUN fields. Unedited fields retain the source
/// profile's values; missing values receive the application's normal defaults.
fn apply_tun(root: &mut Mapping, s: &Settings) {
    let t = &s.tun;
    let mut tun = match root.remove("tun") {
        Some(Value::Mapping(m)) => m,
        _ => Mapping::new(),
    };
    for (name, packages) in [
        ("include-package", &t.include_package),
        ("exclude-package", &t.exclude_package),
    ] {
        if s.overrides.contains(&format!("tun.{name}")) || !tun.contains_key(name) {
            tun.insert(
                key(name),
                Value::Sequence(packages.iter().cloned().map(Value::from).collect()),
            );
        }
    }
    let mut set = |name: &str, value: Value| {
        if s.overrides.contains(&format!("tun.{name}")) || !tun.contains_key(name) {
            tun.insert(key(name), value);
        }
    };
    set("enable", Value::from(t.enable));
    if !t.enable {
        root.insert(key("tun"), Value::Mapping(tun));
        return;
    }
    set("stack", Value::from(t.stack.clone()));
    set("auto-route", Value::from(t.auto_route));
    set("strict-route", Value::from(t.strict_route));
    set(
        "auto-detect-interface",
        Value::from(t.auto_detect_interface),
    );
    set(
        "dns-hijack",
        Value::Sequence(
            t.dns_hijack
                .iter()
                .map(|d| Value::from(d.clone()))
                .collect(),
        ),
    );
    if t.dns_mode.is_empty() {
        tun.remove("dns-mode");
    } else {
        if s.overrides.contains("tun.dns-mode") || !tun.contains_key("dns-mode") {
            tun.insert(key("dns-mode"), Value::from(t.dns_mode.clone()));
        }
    }
    if !t.device.trim().is_empty() {
        if s.overrides.contains("tun.device") || !tun.contains_key("device") {
            tun.insert(key("device"), Value::from(t.device.trim()));
        }
    } else if s.overrides.contains("tun.device") {
        tun.remove("device");
    }
    if let Some(mtu) = t.mtu {
        if s.overrides.contains("tun.mtu") || !tun.contains_key("mtu") {
            tun.insert(key("mtu"), Value::from(mtu));
        }
    } else if s.overrides.contains("tun.mtu") {
        tun.remove("mtu");
    }
    root.insert(key("tun"), Value::Mapping(tun));

    // Hijacked DNS is answered by mihomo's DNS module; if the profile leaves it
    // disabled, every lookup fails and TUN "breaks the internet".
    let dns_enabled = root
        .get("dns")
        .and_then(|d| d.get("enable"))
        .and_then(Value::as_bool)
        .unwrap_or(false);
    if !dns_enabled {
        let mut dns = match root.remove("dns") {
            Some(Value::Mapping(m)) => m,
            _ => Mapping::new(),
        };
        dns.insert(key("enable"), Value::from(true));
        let mut default = |k: &str, v: Value| {
            if !dns.contains_key(k) {
                dns.insert(key(k), v);
            }
        };
        default("enhanced-mode", Value::from("fake-ip"));
        default("fake-ip-range", Value::from("198.18.0.1/16"));
        default(
            "fake-ip-filter",
            Value::Sequence(
                [
                    "*.lan",
                    "*.local",
                    "*.localdomain",
                    "+.msftconnecttest.com",
                    "+.msftncsi.com",
                ]
                .into_iter()
                .map(Value::from)
                .collect(),
            ),
        );
        if s.overrides.contains("dns.nameserver") {
            dns.remove("nameserver");
        }
        let mut default = |k: &str, v: Value| {
            if !dns.contains_key(k) {
                dns.insert(key(k), v);
            }
        };
        default(
            "nameserver",
            Value::Sequence(
                t.dns_nameservers
                    .iter()
                    .map(|n| Value::from(n.clone()))
                    .collect(),
            ),
        );
        root.insert(key("dns"), Value::Mapping(dns));
    }
}

/// Build the selected profile using the same overrides as core start/reload, without side effects.
pub fn preview_runtime_config(
    state: &AppState,
    profile_id: &str,
    content: &str,
) -> Result<(String, Settings)> {
    let routed = crate::routing::apply_profile(state, Some(profile_id), content)?;
    preview_routed_runtime_config(state, profile_id, content, &routed)
}

pub fn preview_routed_runtime_config(
    state: &AppState,
    profile_id: &str,
    content: &str,
    routed: &str,
) -> Result<(String, Settings)> {
    let mut settings = state
        .settings
        .lock()
        .unwrap()
        .clone()
        .resolve_profile(content)?;
    let status = state.core.lock().unwrap().status(&settings);
    if status.running {
        settings.controller_port = reqwest::Url::parse(&status.controller)
            .ok()
            .and_then(|u| u.port_or_known_default())
            .unwrap_or(settings.controller_port);
        settings.secret = status.secret;
        settings
            .overrides
            .extend(["external-controller".into(), "secret".into()]);
    }
    let apps = state.app_rules.lock().unwrap().clone();
    let groups = state
        .custom_groups
        .lock()
        .unwrap()
        .for_profile(Some(profile_id))
        .to_vec();
    let runtime = build_runtime_config_with_groups(
        routed,
        &settings,
        apps.rules_for_profile(Some(profile_id)),
        apps.order_override(Some(profile_id)),
        &groups,
    )?;
    Ok((runtime, settings))
}
